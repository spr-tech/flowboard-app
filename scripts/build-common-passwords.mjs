// Rebuilds src/server/auth/commonPasswords.ts from SecLists' "10k most common" list (MIT licence):
// https://github.com/danielmiessler/SecLists/blob/master/Passwords/Common-Credentials/10k-most-common.txt
//
//   node scripts/build-common-passwords.mjs <path to 10k-most-common.txt> <minimum length>
//
// Only entries at least the minimum password length are kept: shorter ones already fail that
// rule, so leaving them out rejects exactly the same passwords. Lowercased and de-duplicated,
// because the check ignores case. Run it again if PASSWORD_MIN_LENGTH changes.
import { readFileSync, writeFileSync } from "node:fs";

const [source, minimum] = process.argv.slice(2);
if (!source || !minimum) {
  console.error("Usage: node scripts/build-common-passwords.mjs <10k-most-common.txt> <minimum length>");
  process.exit(1);
}

const entries = [
  ...new Set(
    readFileSync(source, "utf8")
      .split(/\r?\n/)
      .map((line) => line.trim().toLowerCase())
      .filter((line) => line.length >= Number(minimum))
  ),
].sort();

writeFileSync(
  "src/server/auth/commonPasswords.ts",
  `// Generated by scripts/build-common-passwords.mjs from SecLists' 10k most common passwords (MIT),
// keeping the ${entries.length} entries of ${minimum}+ characters (shorter ones fail the length rule anyway).
// Lowercase; the check ignores case. Server only: never import this into browser code.
export const COMMON_PASSWORDS: ReadonlySet<string> = new Set(${JSON.stringify(entries)});
`
);
console.log(`Wrote ${entries.length} entries.`);
